fn app(state: AppState) -> Router {
    routes()
        .into_iter()
        .fold(Router::new(), |router, (path, method)| {
            router.route(path, method)
        })
        .layer(middleware::from_fn_with_state(state.clone(), origin_check))
        .layer(middleware::from_fn_with_state(
            state.clone(),
            session_refresh,
        ))
        .layer(middleware::from_fn(security_headers))
        // The request span records the path, not the full URI: a query
        // string is never a safe thing to log.
        .layer(
            tower_http::trace::TraceLayer::new_for_http().make_span_with(|req: &Request| {
                tracing::debug_span!(
                    "request",
                    method = %req.method(),
                    path = %req.uri().path(),
                )
            }),
        )
        .with_state(state)
}

/// The binary's log subscriber, taking the filter and writer so a test can
/// drive this exact one without depending on the ambient `RUST_LOG`. JSON, one
/// object per record: the structured fields (`sub`, `issuer`, `cause`, ...)
/// are what an outage is triaged off, and the encoder escapes every C0
/// control char in every field however a call site records it — `%`
/// included. It does not escape U+2028/U+2029/NEL, so recording untrusted
/// values with `?` and a length cap still matters.
fn log_subscriber<W>(
    filter: tracing_subscriber::EnvFilter,
    writer: W,
) -> impl tracing::Subscriber + Send + Sync + 'static
where
    W: for<'a> tracing_subscriber::fmt::MakeWriter<'a> + Send + Sync + 'static,
{
    tracing_subscriber::fmt()
        .json()
        .with_env_filter(filter)
        .with_writer(writer)
        .finish()
}

#[tokio::main]
async fn main() {
    use tracing_subscriber::util::SubscriberInitExt;
    let filter = tracing_subscriber::EnvFilter::try_from_default_env()
        .unwrap_or_else(|_| "ops_console=info,tower_http=info".into());
    log_subscriber(filter, std::io::stdout).init();

    // Fail-closed: any missing/invalid config value refuses startup (AC10).
    let config = match config::Config::from_env() {
        Ok(c) => c,
        Err(e) => {
            eprintln!("ops-console refusing to start: {e}");
            std::process::exit(1);
        }
    };
    tracing::info!(?config, "ops-console starting");

    let listen = config.listen_addr.clone();
    let metrics_listen = config.store.as_ref().map(|s| s.metrics_addr.clone());
    let state = AppState::new(config);
    let listener = tokio::net::TcpListener::bind(&listen)
        .await
        .expect("failed to bind");
    tracing::info!("ops-console listening on {listen}");
    if let (Some(addr), Some(store)) = (metrics_listen, state.store.as_ref()) {
        let metrics = tokio::net::TcpListener::bind(&addr)
            .await
            .expect("failed to bind the metrics listener");
        tracing::info!("ops-console metrics listening on {addr}");
        let router = metrics_app(store.committed.clone());
        // Ends with the process: the main server's shutdown returns from main.
        tokio::spawn(async move {
            if let Err(e) = axum::serve(metrics, router).await {
                tracing::error!(error = %e, "metrics listener stopped");
            }
        });
    }

    axum::serve(listener, app(state))
        .with_graceful_shutdown(shutdown_signal())
        .await
        .expect("server error");
}

async fn shutdown_signal() {
    let ctrl_c = tokio::signal::ctrl_c();
    let mut sigterm = tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())
        .expect("failed to register SIGTERM handler");
    tokio::select! {
        _ = ctrl_c => tracing::info!("received SIGINT, shutting down…"),
        _ = sigterm.recv() => tracing::info!("received SIGTERM, shutting down…"),
    }
}

